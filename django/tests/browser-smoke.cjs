/* Run only against tests/browser_fixture.py in an isolated validation instance. */
const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const base=process.env.TEST_BASE_URL||'http://127.0.0.1:8091';
const output=path.resolve(process.env.TEST_OUTPUT||'test-results/browser');
(async()=>{
  await fs.mkdir(output,{recursive:true});
  const browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('dialog',dialog=>dialog.accept());
  await page.goto(base+'/connexion');
  await page.getByLabel('Email',{exact:true}).fill('demo@example.test');
  await page.getByLabel('Mot de passe',{exact:true}).fill('DemoForBrowser123!');
  await Promise.all([page.waitForURL('**/app'),page.getByRole('button',{name:'Se connecter',exact:true}).click()]);
  await page.screenshot({path:path.join(output,'dashboard.png'),fullPage:true});
  await page.goto(base+'/app/devis/nouveau');
  await page.locator('select[name="customer_uid"]').selectOption({label:'Maison des Exemples · FR'});
  await page.getByLabel('Objet',{exact:true}).fill('Validation navigateur '+Date.now());
  await page.getByLabel('Désignation',{exact:true}).fill('Conception et réalisation — test fictif');
  await page.getByLabel('Quantité',{exact:true}).fill('3');
  await page.getByLabel('Prix unitaire HT',{exact:true}).fill('125.50');
  await page.getByLabel('Remise',{exact:true}).fill('10');
  await page.waitForFunction(()=>document.getElementById('save-status').textContent==='Brouillon enregistré');
  const draft=await page.locator('input[name="document_uid"]').inputValue();
  assert.match(draft,/^[a-f0-9]{32}$/);
  assert.match(await page.locator('#totals').innerText(),/406.62/);
  await page.screenshot({path:path.join(output,'quote-editor.png'),fullPage:true});
  await Promise.all([page.waitForURL('**/app/devis/'+draft),page.getByRole('button',{name:'Enregistrer le document',exact:true}).click()]);
  assert.match(await page.locator('main').innerText(),/406,62/);
  await Promise.all([page.waitForLoadState('networkidle'),page.getByRole('button',{name:'Marquer accepté',exact:true}).click()]);
  await page.getByRole('button',{name:'Facturer le solde',exact:true}).waitFor();
  await Promise.all([page.waitForURL(/\/app\/factures\/[a-f0-9]{32}$/),page.getByRole('button',{name:'Facturer le solde',exact:true}).click()]);
  const invoice=page.url();
  await Promise.all([page.waitForLoadState('networkidle'),page.getByRole('button',{name:'Générer Factur-X',exact:true}).click()]);
  await page.locator('a').filter({hasText:/facturx ·/}).waitFor();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('link',{name:'Télécharger le PDF',exact:true}).click();
  const download=await downloadPromise;await download.saveAs(path.join(output,'factur-x.pdf'));
  const pdf=await fs.readFile(path.join(output,'factur-x.pdf'));assert.equal(pdf.subarray(0,5).toString(),'%PDF-');
  await Promise.all([page.waitForLoadState('networkidle'),page.getByRole('button',{name:'Émettre par email',exact:true}).click()]);
  await page.locator('.badge.sent').first().waitFor();
  await page.screenshot({path:path.join(output,'invoice.png'),fullPage:true});
  await page.goto(base+'/app/finances/transactions');
  await page.getByLabel('Libellé',{exact:true}).fill('Paiement fictif validation');
  await page.getByLabel('Montant',{exact:true}).fill('100');
  await Promise.all([page.waitForLoadState('networkidle'),page.getByRole('button',{name:'Enregistrer',exact:true}).click()]);
  const last=page.locator('tbody tr').filter({hasText:'Paiement fictif validation'}).first();
  const invoiceUid=invoice.split('/').pop();
  await last.locator('select[name="document_uid"]').selectOption(invoiceUid);
  await Promise.all([page.waitForLoadState('networkidle'),last.getByRole('button',{name:'Rapprocher',exact:true}).click()]);
  await page.goto(invoice);
  assert.match(await page.locator('.totals-display').innerText(),/306,62/);
  await page.goto(base+'/app');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile page overflows');
  const source=await context.request.get(base+'/source/archive');assert.equal(source.status(),200);
  assert.equal(errors.length,0,errors.join('\n'));
  await fs.writeFile(path.join(output,'report.json'),JSON.stringify({ok:true,flow:['login','quote_autosave','quote_accept','invoice_conversion','facturx','pdf_download','email_outbox','partial_payment','mobile','source_archive'],javascript_errors:errors},null,2));
  await browser.close();
  console.log('Browser smoke passed: 11 checks; PDF and screenshots saved.');
})().catch(error=>{console.error(error);process.exit(1)});
