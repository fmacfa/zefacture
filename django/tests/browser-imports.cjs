const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const base=process.env.TEST_BASE_URL||'http://127.0.0.1:8091';
const output=path.resolve('test-results/browser');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/connexion');await page.getByLabel('Email',{exact:true}).fill('demo@example.test');
  await page.getByLabel('Mot de passe',{exact:true}).fill('DemoForBrowser123!');
  await Promise.all([page.waitForURL('**/app'),page.getByRole('button',{name:'Se connecter',exact:true}).click()]);
  await page.goto(base+'/app/devis/nouveau');
  await page.getByRole('button',{name:'+ Nouveau client',exact:true}).click();
  const dialog=page.locator('dialog');
  await dialog.getByLabel('Nom / raison sociale',{exact:true}).fill('Client rapide fictif');
  await dialog.getByLabel('Email',{exact:true}).fill('quick@example.test');
  await dialog.getByRole('button',{name:'Créer le client',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert.equal(await page.locator('select[name=customer_uid] option:checked').textContent(),'Client rapide fictif');
  await page.goto(base+'/app/imports');
  await page.locator('input[name=file]').setInputFiles(process.env.TEST_IMPORT_FILE||path.join(output,'factur-x.pdf'));
  await Promise.all([page.waitForURL(/\/app\/imports\/[a-f0-9]{32}$/),page.getByRole('button',{name:'Importer',exact:true}).click()]);
  const ingestion=page.url();
  await page.getByRole('button',{name:'Transcrire',exact:true}).click();
  for(let attempt=0;attempt<30;attempt++){
    await page.goto(ingestion);
    if((await page.locator('textarea[name=transcription_text]').inputValue()).includes('Atelier Démonstration'))break;
    await page.waitForTimeout(1000);
  }
  assert.match(await page.locator('textarea[name=transcription_text]').inputValue(),/Atelier Démonstration/);
  await page.getByLabel('Nom du fournisseur',{exact:true}).fill('Fournisseur test OCR');
  await page.getByLabel('Numéro de facture',{exact:true}).fill('SUP-BROWSER-'+Date.now());
  await page.getByLabel("Date d'émission",{exact:true}).fill('2026-10-25');
  await page.getByLabel('Échéance',{exact:true}).fill('2026-11-24');
  await page.getByLabel('Désignation',{exact:true}).fill('Achat fictif importé');
  await page.getByLabel('Quantité',{exact:true}).fill('1');
  await page.getByLabel('Prix unitaire HT',{exact:true}).fill('100');
  await page.screenshot({path:path.join(output,'import-review.png'),fullPage:true});
  await Promise.all([page.waitForURL(/\/app\/reception\/[a-f0-9]{32}$/),page.getByRole('button',{name:'Valider et créer la facture reçue',exact:true}).click()]);
  assert.match(await page.locator('main').innerText(),/120,00/);
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:"Télécharger l’original",exact:true}).click()]);
  const expectedExtension=process.env.TEST_IMPORT_FILE?path.extname(process.env.TEST_IMPORT_FILE):'.pdf';
  assert.equal(path.extname(download.suggestedFilename()),expectedExtension);
  assert.equal(errors.length,0,errors.join('\n'));
  await fs.writeFile(path.join(output,process.env.TEST_IMPORT_FILE?'ocr-report.json':'imports-report.json'),JSON.stringify({ok:true,flow:['quick_customer','upload','queued_local_transcription','manual_review_form','supplier_invoice_conversion','original_download'],javascript_errors:errors},null,2));
  await browser.close();console.log('Browser imports passed: 6 checks.');
})().catch(error=>{console.error(error);process.exit(1)});
